"""
The personal obligation: normative floor vs observed hours, and what separates them.

This is the reporting structure for a decomposition the repo cannot yet complete,
built so that the part it cannot do is visible instead of absorbed.

THE IDENTITY
------------
Observed time use is not the entropy obligation. It is

    observed  =  obligation  −  deferred  +  extraction

where `deferred` is obligation gone unserved (it shows up physiologically, never
in a diary) and `extraction` is institutionally-induced hours that resist no
entropy — commuting generated by settlement pattern, paperwork generated by the
administration of paperwork. One observable, three unknowns, so no amount of work
on the hours series alone separates them.

The normative floor breaks the deadlock from one side: a floor computed from
physical quantities at a stated delivery productivity is `obligation` by
construction, because nothing in it derives from what anyone was observed to do
or paid. That is the same move that closed the infrastructure determinacy gap
(doctrine spread 10.26× on the monetized path, 1.000× on the physical floor).

WHAT THIS MODULE REPORTS, AND WHAT IT REFUSES TO
--------------------------------------------------
The shipped basket prices ONE component of seven — 6.9% of the obligation by the
desk estimate's own weights. So the residual is not `extraction − deferred`; it is

    observed − floor_priced  =  floor_unpriced  −  deferred  +  extraction

— still three unknowns, now with the largest of them being the repo's own
incompleteness. `identity_report()` returns the residual under that name and
leaves `deferred` and `extraction` as None. It does not attribute.

This is deliberate and it is the finding: **the extraction wedge is not
identified at current basket coverage.** Raising coverage is the prerequisite for
quantifying it, and until then a number for extraction would be a fitted
residual wearing a theory's clothes — the floating-basket failure one level up.
An independent estimator (a cross-country frontier panel: the same physical
basket delivered in fewer hours elsewhere at comparable capital) is what would
identify it without a residual, and no such panel is ingested here.

Layer: scenarios/ imports core/ and reference/ — pure, no I/O beyond the shipped
reference extracts.

ε-coherence: `floor_arc()` exercises the floor at ε ∈ {0, 0.40, 0.99}. The floor
is ε-invariant in its priced components (a physical requirement does not depend
on the automation level) and a step function in which components have a delivery
path at all.

Reference: the personal-obligation handoff §0.2, §2, §3.3;
the knowledge-base closure note Finding B.
"""

