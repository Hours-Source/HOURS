def regenerative_offset(
    labor_type: str,
    regenerative_hours: float,
    epsilon: float = 0.40,
) -> dict:
    """
    Calculate the future EOH reduction from a regenerative labor investment.

    Maintenance labor fulfills current EOH (creating TEH). Regenerative labor
    does the same — it fulfills current EOH and creates TEH at the worker's
    multiplier rate — but additionally reduces future EOH generation rates.

    This distinction carries significant implications for stewardship planning:
    a collective that invests in regenerative labor today can reduce its total
    entropy obligation over the medium term, even before automation rises.

    Note: TEH creation from regenerative labor is handled by the standard
    teh_created() pipeline. This function returns only the *additional*
    future benefit that distinguishes regenerative from maintenance labor.

    Args:
        labor_type: Key into REGENERATIVE_PROFILES (e.g., "composting",
                    "preventive_maintenance", "education_training").
        regenerative_hours: Hours of regenerative labor performed.
        epsilon: Automation level. At higher ε, some regenerative benefits
                 are amplified (automated monitoring extends impact).

    Returns:
        dict: {
          "labor_type": str,
          "domain": str,
          "hours_worked": float,
          "current_eoh_fulfilled": float,     (= hours, standard TEH creation)
          "future_eoh_reduction_per_year": float,  (annual EOH saved going forward)
          "amortization_years": int,
          "lifetime_eoh_savings": float,      (total EOH saved over amortization)
          "epsilon_leverage": float,          (automation amplification factor)
        }

    Raises:
        KeyError: If labor_type is not in REGENERATIVE_PROFILES.

    Reference: Mission Statement §"Regenerative offset" — "Some labor reduces
    future EOH rather than fulfilling current EOH. Composting enriches soil,
    reducing future agricultural labor needs. Preventive maintenance extends
    asset life, lowering future obligation generation rates."
    """
    if labor_type not in REGENERATIVE_PROFILES:
        raise KeyError(
            f"Unknown labor_type: {labor_type!r}. "
            f"Valid types: {list(REGENERATIVE_PROFILES.keys())}"
        )

    profile = REGENERATIVE_PROFILES[labor_type]

    # At higher ε, automated monitoring and precision tools extend the reach
    # of regenerative labor. Leverage grows modestly with automation.
    epsilon_leverage = 1.0 + REGEN_AUTOMATION_LEVERAGE_MAX * epsilon

    per_year = regenerative_hours * profile["eoh_saved_per_hour"] * epsilon_leverage
    amort    = profile["amortization_years"]
    lifetime = per_year * amort

    return {
        "labor_type":                    labor_type,
        "domain":                        profile["domain"],
        "description":                   profile["description"],
        "hours_worked":                  regenerative_hours,
        "current_eoh_fulfilled":         regenerative_hours,   # standard fulfillment
        "future_eoh_reduction_per_year": per_year,
        "amortization_years":            amort,
        "lifetime_eoh_savings":          lifetime,
        "epsilon_leverage":              epsilon_leverage,
    }


def regenerative_vs_maintenance_comparison(
    labor_hours: float,
    regen_type: str,
    current_eoh_demand: float,
    epsilon: float = 0.40,
) -> dict:
    """
    Compare the full impact of investing labor hours in regenerative vs. maintenance.

    Both modes create TEH (at the worker's multiplier rate). Regenerative labor
    additionally reduces future EOH obligations, which compounds over time.
    This comparison quantifies the long-term advantage of regenerative investment.

    Args:
        labor_hours: Hours of labor to compare.
        regen_type: Regenerative labor type (from REGENERATIVE_PROFILES).
        current_eoh_demand: Current EOH demand this labor would fulfill if
                            used for maintenance.
        epsilon: Automation level.

    Returns:
        dict with "maintenance" and "regenerative" sub-dicts, plus "net_advantage"
        showing the total EOH reduction advantage of the regenerative choice.

    Reference: Mission Statement §"Regenerative offset" — tracking the distinction
    "carries significant implications for long-term stewardship planning."
    """
    regen = regenerative_offset(regen_type, labor_hours, epsilon)

    maintenance_impact = {
        "current_eoh_fulfilled":     min(labor_hours, current_eoh_demand),
        "future_eoh_reduction":      0.0,
        "lifetime_eoh_impact":       min(labor_hours, current_eoh_demand),
    }

    regenerative_impact = {
        "current_eoh_fulfilled":     regen["current_eoh_fulfilled"],
        "future_eoh_reduction_per_year": regen["future_eoh_reduction_per_year"],
        "amortization_years":        regen["amortization_years"],
        "lifetime_eoh_impact":       (regen["current_eoh_fulfilled"]
                                      + regen["lifetime_eoh_savings"]),
    }

    net_advantage = (regenerative_impact["lifetime_eoh_impact"]
                     - maintenance_impact["lifetime_eoh_impact"])

    return {
        "maintenance":    maintenance_impact,
        "regenerative":   regenerative_impact,
        "net_advantage":  net_advantage,   # positive = regenerative wins long-term
        "epsilon":        epsilon,
    }


