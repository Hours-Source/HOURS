def eoh_reduction_ratio(
    production_cost_eoh: float,
    annual_maintenance_eoh: float,
    annual_eoh_eliminated: float,
    design_life: float,
    epsilon: float = 0.40,
) -> dict:
    """
    Research-only: investment analysis tool, not wired into dashboard or simulation.

    Used for off-line analysis of whether a specific asset's EOH reduction justifies
    its production and maintenance cost. Call from analytical scripts or test scenarios;
    do not call from dashboard.py or simulate_period() — investment ranking is not
    part of the period-by-period fiscal pipeline.

    Does this asset eliminate more system EOH than it costs to build and maintain?

    The production economy's core investment criterion: build what reduces
    aggregate EOH below its own lifetime cost. A factory is valuable not because
    it generates profit but because it reduces the total system entropy labor required.
    If a factory's infrastructure EOH (lifetime maintenance burden) exceeds the
    system EOH it eliminates, it is a net loss and should be written down
    (Mission Statement: production economy logic).

    Note: annual_eoh_eliminated reduces infrastructure/ecological/knowledge EOH
    at the system level. Personal EOH (biological needs) is not reduced by capital.

    At higher ε: automation handles an increasing share of the maintenance burden,
    so the effective maintenance cost in human-labor terms shrinks. This means
    an asset that appears marginal at ε=0 may become clearly worth building at ε=0.40.

    Args:
        production_cost_eoh: One-time EOH to build the asset (hours).
        annual_maintenance_eoh: Annual EOH to maintain the asset (hours/year).
        annual_eoh_eliminated: Annual system EOH (i/e/k domains) reduced by
                               this asset (hours/year) — piped water eliminates
                               ecological/infrastructure water-management burden.
        design_life: Asset's expected useful life (years).
        epsilon: Automation level. Scales the human-labor component of maintenance.

    Returns:
        dict: {
          "production_cost_eoh": float,
          "lifetime_maintenance_eoh": float,   (human-labor share only)
          "total_eoh_cost": float,             (production + maintenance)
          "lifetime_eoh_benefit": float,
          "net_eoh_reduction": float,          (benefit - cost; positive = good)
          "ratio": float,                      (<1.0 = net positive; >1.0 = net loss)
          "net_positive": bool,
          "payback_years": float | None,       (years until benefit exceeds cost)
          "epsilon": float,
        }

    Reference: Mission Statement §"Infrastructure EOH — the economic logic of
    infrastructure investment: build what generates less EOH than it eliminates";
    §"The production economy — A factory is valuable not because it generates
    profit but because it reduces the total human labor required to meet personal
    entropy obligations."
    """
    if design_life <= 0:
        raise ValueError(f"design_life must be positive, got {design_life}")
    if annual_eoh_eliminated < 0:
        raise ValueError("annual_eoh_eliminated cannot be negative")

    # At higher ε, automation handles more maintenance — human-labor share shrinks
    human_maint_fraction = 1.0 - epsilon
    lifetime_maint_human = annual_maintenance_eoh * design_life * human_maint_fraction

    # Production cost is incurred at ε=0 regardless (building requires human labor)
    # but scale by (1-ε) as well if automation assists construction
    effective_prod_cost = production_cost_eoh * (0.5 + 0.5 * (1.0 - epsilon))

    total_cost    = effective_prod_cost + lifetime_maint_human
    total_benefit = annual_eoh_eliminated * design_life

    ratio = total_cost / max(total_benefit, 1.0)
    net   = total_benefit - total_cost

    # Payback: years until cumulative benefit exceeds total cost
    if annual_eoh_eliminated > annual_maintenance_eoh * human_maint_fraction:
        annual_net = (annual_eoh_eliminated
                      - annual_maintenance_eoh * human_maint_fraction)
        payback_years = effective_prod_cost / annual_net if annual_net > 0 else None
    else:
        payback_years = None  # never pays back

    return {
        "production_cost_eoh":         effective_prod_cost,
        "lifetime_maintenance_eoh":    lifetime_maint_human,
        "total_eoh_cost":              total_cost,
        "lifetime_eoh_benefit":        total_benefit,
        "net_eoh_reduction":           net,
        "ratio":                       ratio,
        "net_positive":                ratio < 1.0,
        "payback_years":               payback_years,
        "epsilon":                     epsilon,
    }


def rank_investment_candidates(
    candidates: list[dict],
    epsilon: float = 0.40,
) -> list[dict]:
    """
    Research-only: investment ranking tool, not wired into dashboard or simulation.

    Rank infrastructure investment candidates by EOH reduction efficiency.

    Evaluates each candidate using eoh_reduction_ratio() and ranks by net EOH
    reduction per unit of production cost (highest return first). Candidates
    with ratio > 1.0 (net EOH loss) are flagged but still included so the
    caller can see the full landscape.

    Each candidate dict must contain:
        - "name": str
        - "production_cost_eoh": float
        - "annual_maintenance_eoh": float
        - "annual_eoh_eliminated": float
        - "design_life": float

    Args:
        candidates: List of proposed asset dicts.
        epsilon: Automation level (affects maintenance cost calculation).

    Returns:
        List of candidates enriched with eoh_reduction_ratio() results,
        sorted by net_eoh_reduction descending (best first).

    Reference: Mission Statement §"The production economy — build what maximizes
    net EOH reduction per unit of maintenance obligation."
    """
    results = []
    for c in candidates:
        analysis = eoh_reduction_ratio(
            production_cost_eoh=c["production_cost_eoh"],
            annual_maintenance_eoh=c["annual_maintenance_eoh"],
            annual_eoh_eliminated=c["annual_eoh_eliminated"],
            design_life=c["design_life"],
            epsilon=epsilon,
        )
        results.append({**c, **analysis})

    # Sort by net EOH reduction (highest first = most worth building)
    results.sort(key=lambda x: x["net_eoh_reduction"], reverse=True)
    return results


def optimal_investment(
    available_labor_eoh: float,
    candidates: list[dict],
    epsilon: float = 0.40,
) -> dict:
    """
    Research-only: investment allocation tool, not wired into dashboard or simulation.

    Greedily allocate available production-labor EOH to maximize net EOH reduction.

    Given a fixed budget of labor hours for capital investment, determines
    which assets to build in priority order. An asset is included if:
    1. It has a positive net_eoh_reduction (ratio < 1.0)
    2. Available labor covers its production_cost_eoh

    The greedy approach is appropriate here because EOH reduction benefits
    are roughly additive across independent assets.

    Args:
        available_labor_eoh: Labor hours available for capital investment.
        candidates: List of proposed asset dicts (same format as rank_investment_candidates).
        epsilon: Automation level.

    Returns:
        dict: {
          "funded": list[dict],            (assets to build, in priority order)
          "unfunded": list[dict],          (not built — insufficient labor or net-negative)
          "net_negative": list[dict],      (excluded: ratio > 1.0)
          "total_cost_eoh": float,
          "total_net_eoh_reduction": float,
          "labor_utilization": float,      (fraction of available_labor used)
          "remaining_labor": float,
        }

    Reference: Mission Statement §"The production economy — optimal_investment:
    where should the next hour of production labor go to maximize net EOH reduction?"
    """
    ranked = rank_investment_candidates(candidates, epsilon)

    # Separate net-positive from net-negative
    worthwhile = [r for r in ranked if r["net_positive"]]
    net_neg    = [r for r in ranked if not r["net_positive"]]

    funded   = []
    unfunded = []
    remaining = available_labor_eoh

    for asset in worthwhile:
        cost = asset["production_cost_eoh"]
        if cost <= remaining:
            funded.append(asset)
            remaining -= cost
        else:
            unfunded.append(asset)

    total_cost = sum(a["production_cost_eoh"] for a in funded)
    total_net  = sum(a["net_eoh_reduction"] for a in funded)

    return {
        "funded":                  funded,
        "unfunded":                unfunded,
        "net_negative":            net_neg,
        "total_cost_eoh":          total_cost,
        "total_net_eoh_reduction": total_net,
        "labor_utilization":       total_cost / max(available_labor_eoh, 1.0),
        "remaining_labor":         remaining,
    }


