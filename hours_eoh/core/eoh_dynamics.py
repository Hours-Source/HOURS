# Deferred EOH (the maintenance deficit)
# ---------------------------------------------------------------------------

def deferred_eoh(
    accumulated_eoh: float,
    fulfilled_eoh: float,
) -> float:
    """
    The maintenance deficit: accumulated EOH obligation minus what was fulfilled.

    This is the structural gap that EOH compounding acts on. Deferred EOH
    is not a monetary debt — no one earns TEH from it existing. It persists
    until labor is directed toward it or the underlying capital fails.

    Args:
        accumulated_eoh: Total EOH generated by this asset to date (hours).
        fulfilled_eoh: Total EOH fulfilled toward this asset to date (hours).

    Returns:
        Deferred EOH (hours). Non-negative. Zero means fully maintained.

    Reference: Mission Statement §"The dual ledger" — "The gap between
    accumulated EOH and fulfilled EOH constitutes deferred maintenance —
    a deficit that is visible, quantifiable, and structurally distinct
    from monetary debt."
    """
    return max(0.0, accumulated_eoh - fulfilled_eoh)


# ---------------------------------------------------------------------------
# EOH Compounding (threshold-based, NOT exponential)
# ---------------------------------------------------------------------------

# Spike factors by asset type: how severe is the threshold failure event?
# Mission Statement: "stone bridge: slow; software: fast; ecosystem: slow then spike"
_SPIKE_FACTORS = {
    "stone_bridge":  1.5,   # structural failure is significant but moderate
    "software":      3.0,   # fast decay, failure is severe and rapid
    "ecosystem":     2.0,   # slow then spike (threshold ecology collapse)
    "building":      1.8,
    "power_grid":    2.2,   # critical systems fail dramatically at threshold
    "generic_infra": 1.9,
}


def eoh_compounding(
    deferred: float,
    asset_type: str,
    time_deferred: float,
    epsilon: float = 0.40,
) -> float:
    """
    Additional EOH generated by unfulfilled obligations over time.

    CRITICAL: This function returns additional EOH obligation — it does NOT
    create TEH. Only labor that fulfills EOH creates TEH. EOH compounding
    generates obligation without labor; TEH is created only when someone
    actually does the work. This is the key distinction from interest.

    The behavior is intentionally threshold-based and discontinuous:

    Pre-threshold (t < T):
      Slow, sub-linear growth. The system is degrading but still functional.
      Compounding is minor — routine neglect has moderate consequences.

    At threshold (t = T):
      Discontinuous spike. Structural failure event. The maintenance deficit
      suddenly demands vastly more labor to address (or rebuild from scratch).
      This is the "long periods of accumulation punctuated by sharp failure"
      described in the Mission Statement.

    Post-threshold (t > T):
      Rapid, power-law escalation. The system is in collapse; each additional
      period of neglect costs disproportionately more to address.

    Different asset types have different threshold ages and escalation profiles:
    - stone_bridge: threshold at 80 years, moderate escalation
    - software: threshold at 5 years, severe rapid escalation
    - ecosystem: threshold at 200 years, but spikes hard when breached

    Args:
        deferred: Accumulated deferred EOH (hours) — the maintenance deficit.
        asset_type: Key into ASSET_TYPES / _SPIKE_FACTORS. Use "generic_infra"
                    for unknown asset types.
        time_deferred: Time (years) since maintenance deficit began accumulating.
        epsilon: Automation level. At higher ε, automated monitoring may
                 catch some deterioration earlier, slightly softening the spike.

    Returns:
        Additional EOH generated by the compounding deficit (hours).
        Add to the asset's deferred_eoh to get total obligation.

    Raises:
        KeyError: If asset_type is not in ASSET_TYPES.

    Reference: Mission Statement §"EOH and compounding" — "Long periods of slow
    accumulation are punctuated by sharp threshold failures — a pattern that bears
    no resemblance to compound interest curves." §"Condition III — Zero Interest":
    EOH compounding ≠ monetary interest; no TEH created without labor.
    """
    if deferred <= 0 or time_deferred <= 0:
        return 0.0

    if asset_type not in ASSET_TYPES:
        raise KeyError(
            f"Unknown asset_type: {asset_type!r}. "
            f"Valid types: {list(ASSET_TYPES.keys())}"
        )

    profile    = ASSET_TYPES[asset_type]
    T          = float(profile["threshold_age"])
    exp        = float(profile["compound_exp"])
    spike      = _SPIKE_FACTORS.get(asset_type, 2.0)

    # Monitoring at higher ε softens the spike (better predictive maintenance)
    monitoring_softener = 1.0 - MONITORING_SPIKE_SOFTENING_MAX * epsilon

    t = float(time_deferred)

    if t < T:
        # Pre-threshold: concave (sub-linear) growth — slow accumulation
        # Formula: deferred × 0.10 × (t/T)^(1/exp)
        # At t→0: approaches 0. At t→T⁻: approaches 0.10 × deferred.
        # (1/exp) > 1 for exp<1, <1 for exp>1 — higher exp → more concave pre-threshold
        t_frac = t / T
        return deferred * PRE_THRESHOLD_COMPOUND_RATE * (t_frac ** (1.0 / exp))

    else:
        # At/beyond threshold: DISCONTINUOUS JUMP + power-law escalation
        # The discontinuity is the "sharp threshold failure" — the system passes
        # a tipping point beyond which its EOH obligation balloons.

        # Pre-threshold baseline (continuous part, just below T)
        pre = deferred * PRE_THRESHOLD_COMPOUND_RATE

        # Discontinuous spike at threshold: spike_factor × deferred
        # Plus power-law escalation with years beyond threshold
        post_years = t - T  # 0 at threshold, positive beyond
        escalation = spike * (1.0 + post_years) ** (exp - 1.0)
        spike_term = deferred * escalation * monitoring_softener

        return pre + spike_term


def compounding_profile(
    asset_type: str,
    deferred: float,
    max_years: float | None = None,
    epsilon: float = 0.40,
    n_points: int = 50,
) -> list[dict]:
    """
    Compute the compounding profile of an asset over time.

    Returns a time series showing additional EOH generated at each time point,
    making the threshold discontinuity visible and auditable.

    Args:
        asset_type: Key into ASSET_TYPES.
        deferred: Maintenance deficit (hours) to compound on.
        max_years: Duration to model. Defaults to 2 × threshold_age.
        epsilon: Automation level.
        n_points: Number of time points.

    Returns:
        List of dicts: [{"year": float, "additional_eoh": float,
                         "is_post_threshold": bool}, ...]

    Reference: Mission Statement §"EOH and compounding" — behavior should be
    transparent and physically auditable (Guardrail I).
    """
    T = float(ASSET_TYPES[asset_type]["threshold_age"])
    end = max_years if max_years is not None else 2.0 * T
    step = end / n_points

    result = []
    for i in range(n_points + 1):
        t = i * step
        result.append({
            "year":             t,
            "additional_eoh":   eoh_compounding(deferred, asset_type, t, epsilon),
            "is_post_threshold": t >= T,
        })
    return result


