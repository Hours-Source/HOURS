"""
EOH Compounding, Regenerative Labor, Infrastructure Investment Logic

EOH compounding models how unfulfilled obligations generate additional EOH
over time. It is explicitly NOT interest, it measures physical reality, not
a social convention. The pattern is threshold-based and discontinuous, not
smooth and exponential. Long periods of slow accumulation are punctuated by
sharp threshold failures.

Regenerative labor differs from maintenance labor: maintenance fulfills current
EOH (and creates TEH); regenerative labor fulfills current EOH AND reduces future
EOH generation rates (composting, preventive maintenance, ecosystem restoration,
education/training).

Infrastructure investment logic answers: does building this asset eliminate more
personal EOH than its own maintenance will cost? The production economy's core
criterion — build what reduces aggregate EOH, not what maximizes return.

Mission Statement: §"EOH and compounding", §"Regenerative offset",
§"The production economy", EOH reduction through capital creation,
§"Infrastructure EOH — the economic logic of infrastructure investment"
"""

