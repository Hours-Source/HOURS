def update_deferred_from_fulfillment(
    current_deferred: float,
    fulfilled_eoh: float,
) -> dict:
    """
    Reduce the deferred EOH backlog by the amount fulfilled this period.

    This closes the feedback loop between EOH fulfillment and the compounding
    model. Without this function, deferred EOH can only grow — assets fulfill
    EOH, but the backlog never shrinks. Calling this after each fulfillment
    event (asset elimination, regenerative labor, direct maintenance) keeps
    the deferred balance accurate for the next call to eoh_compounding().

    Semantics: fulfilled_eoh is the total EOH addressed this period (from
    annual_eoh_eliminated, future_eoh_reduction_per_year from regenerative
    labor, or direct maintenance hours × multiplier). It reduces the backlog
    up to but not beyond the current balance.

    Args:
        current_deferred: Current accumulated deferred EOH (hours). Non-negative.
        fulfilled_eoh: EOH fulfilled toward the backlog this period (hours).
                       Must be non-negative. Excess fulfillment is not carried
                       forward — it only reduces existing backlog.

    Returns:
        dict: {
          "previous_deferred": float,
          "fulfilled_eoh":     float,
          "reduction":         float,   (min(fulfilled_eoh, current_deferred))
          "new_deferred":      float,   (≥ 0; updated balance to store)
          "fully_cleared":     bool,    (True if backlog reaches zero)
          "excess_fulfillment": float,  (fulfilled beyond what was owed; usually 0)
        }

    Reference: Mission Statement §"The dual ledger — the gap between accumulated
    EOH and fulfilled EOH constitutes deferred maintenance; active investment
    must reduce that gap or compounding accelerates."
    """
    current_deferred = max(0.0, current_deferred)
    fulfilled_eoh    = max(0.0, fulfilled_eoh)

    reduction         = min(fulfilled_eoh, current_deferred)
    new_deferred      = current_deferred - reduction
    excess_fulfillment = fulfilled_eoh - reduction

    return {
        "previous_deferred":  current_deferred,
        "fulfilled_eoh":      fulfilled_eoh,
        "reduction":          reduction,
        "new_deferred":       new_deferred,
        "fully_cleared":      new_deferred <= 0.0,
        "excess_fulfillment": excess_fulfillment,
    }


def deferred_eoh_paydown(
    regenerative_result: dict,
    current_deferred: float,
) -> dict:
    """
    Retire accumulated deferred EOH through regenerative labor.

    regenerative_offset() computes how much future EOH a labor investment saves,
    but does not close the deferred backlog — that obligation is a one-way
    ratchet without this function. deferred_eoh_paydown() converts the
    regenerative result into an explicit paydown of the deferred balance,
    making active restoration visible in the ledger (Guardrail I).

    Semantics: the caller reduces their deferred balance (passed to
    ecological_eoh() or total_eoh()) by annual_paydown each year that
    regenerative labor is maintained.

    Args:
        regenerative_result: Return dict from regenerative_offset().
        current_deferred: Current accumulated deferred EOH balance (hours).

    Returns:
        dict: {
          "domain":                          str,
          "annual_paydown":                  float,  (per year; capped at current_deferred)
          "new_deferred_after_one_year":     float,
          "lifetime_paydown":                float,  (if maintained over full amortization period)
          "new_deferred_after_amortization": float,
          "deferred_cleared":                bool,   (one year's labor clears the entire backlog)
          "years_to_clear":                  float | None,  (None if balance is already zero)
        }

    Reference: Mission Statement §"Ecological EOH — the framework makes historical
    neglect visible; active restoration must reduce that visibility proportionally."
    """
    per_year = float(regenerative_result.get("future_eoh_reduction_per_year", 0.0))
    amort    = int(regenerative_result.get("amortization_years", 0))
    domain   = str(regenerative_result.get("domain", ""))

    annual_paydown = min(per_year, current_deferred)
    new_deferred_1 = max(0.0, current_deferred - annual_paydown)

    lifetime_paydown = min(per_year * amort, current_deferred)
    new_deferred_amort = max(0.0, current_deferred - lifetime_paydown)

    if current_deferred <= 0.0:
        years_to_clear = None
    elif per_year <= 0.0:
        years_to_clear = None
    else:
        years_to_clear = current_deferred / per_year

    return {
        "domain":                          domain,
        "annual_paydown":                  annual_paydown,
        "new_deferred_after_one_year":     new_deferred_1,
        "lifetime_paydown":                lifetime_paydown,
        "new_deferred_after_amortization": new_deferred_amort,
        "deferred_cleared":                annual_paydown >= current_deferred,
        "years_to_clear":                  years_to_clear,
    }


# ---------------------------------------------------------------------------
# Regenerative investment required (inverse of regenerative_offset)
# ---------------------------------------------------------------------------

def regenerative_investment_required(
    eoh_reduction_target: float,
    labor_type: str,
    epsilon: float = 0.40,
    years_horizon: int | None = None,
) -> dict:
    """
    Annual labor hours needed to achieve a target future EOH reduction rate.

    Inverts regenerative_offset(): given a desired future_eoh_reduction_per_year,
    computes hours_needed = target / (eoh_saved_per_hour × epsilon_leverage).
    This enables proactive workforce planning — "to reduce ecological EOH by
    50,000 h/yr, how much composting labor must we commit annually?"

    Args:
        eoh_reduction_target: Desired annual EOH reduction (hours/year).
        labor_type: Key into REGENERATIVE_PROFILES.
        epsilon: Automation level. Higher ε amplifies impact via epsilon_leverage.
        years_horizon: Override the profile's default amortization period for
                       the cumulative hours estimate. None → use profile default.

    Returns:
        dict: {
          "labor_type":                    str,
          "domain":                        str,
          "eoh_reduction_target_per_year": float,
          "hours_needed_per_year":         float,
          "cumulative_hours_over_horizon":  float,
          "years_horizon":                 int,
          "epsilon":                       float,
          "epsilon_leverage":              float,
        }

    Raises:
        KeyError: If labor_type is not in REGENERATIVE_PROFILES.

    Reference: Mission Statement §"Regenerative offset — some labor reduces
    future EOH rather than fulfilling current EOH."
    """
    if labor_type not in REGENERATIVE_PROFILES:
        raise KeyError(
            f"Unknown labor_type: {labor_type!r}. "
            f"Valid types: {list(REGENERATIVE_PROFILES.keys())}"
        )

    profile          = REGENERATIVE_PROFILES[labor_type]
    epsilon_leverage = 1.0 + REGEN_AUTOMATION_LEVERAGE_MAX * epsilon
    effective_rate   = profile["eoh_saved_per_hour"] * epsilon_leverage

    hours_needed     = eoh_reduction_target / max(effective_rate, 1e-10)
    horizon          = years_horizon if years_horizon is not None else profile["amortization_years"]
    cumulative_hours = hours_needed * horizon

    return {
        "labor_type":                    labor_type,
        "domain":                        profile["domain"],
        "eoh_reduction_target_per_year": eoh_reduction_target,
        "hours_needed_per_year":         hours_needed,
        "cumulative_hours_over_horizon":  cumulative_hours,
        "years_horizon":                 horizon,
        "epsilon":                       epsilon,
        "epsilon_leverage":              epsilon_leverage,
    }
