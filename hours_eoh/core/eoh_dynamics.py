def maintenance_strategy_compare(
    asset_type: str,
    annual_eoh: float,
    teh_value: float,
    initial_condition: float = 1.0,
    years_horizon: int = 30,
    epsilon: float = 0.40,
    natural_decay_rate: float = HUMAN_CAPITAL_NATURAL_DECAY,
    writedown_threshold: float = 0.20,
) -> dict:
    """
    Compare total human-labor EOH cost of three maintenance strategies over a
    time horizon, helping answer: is continuous maintenance cheaper than
    deferring until write-down or replacement?

    All costs use the human-labor share (1−ε) because automation handles the
    rest of the physical work. Both maintenance and rebuild scale down with
    automation, but the compounding EOH spike (from deferred neglect) is
    partially offset by better monitoring at high ε — making the comparison
    non-trivial and ε-dependent.

    Strategies:
    1. **continuous**: Pay annual_eoh × (1−ε) human-labor hours each year.
       Asset condition stays healthy; no write-down occurs in the horizon.
       Total = annual_eoh × (1−ε) × years_horizon.

    2. **deferred_to_writedown**: Pay no maintenance. Condition degrades per
       asset_condition_trajectory(fulfillment_fraction=0.0). When condition
       drops below writedown_threshold, a write-down fires: rebuild cost =
       teh_value × (1−ε) in human labor, plus compounding EOH from
       eoh_compounding(). After rebuild the asset runs on continuous
       maintenance for the remaining years.

    3. **replace_at_writedown**: Same deferred trajectory and trigger, but
       instead of rebuilding to same spec, the asset is replaced at 85% of
       rebuild cost (new-build with current technology; fewer custom fittings,
       better supply chain). Remaining years on continuous maintenance.

    At very high ε all three costs converge toward zero, but the compounding
    spike's ε-softening (eoh_compounding uses monitoring_softener) still
    differentiates strategies. Long-lived, threshold-sensitive assets (bridges,
    water systems) favor continuous maintenance; short-lived equipment at high
    ε may favor replacement.

    Args:
        asset_type: Key into ASSET_TYPES. Determines compound_exp and spike
                    factor used by eoh_compounding().
        annual_eoh: Annual maintenance EOH demand (hours/year) at full
                    human-labor level (ε=0 equivalent).
        teh_value: Asset's TEH value (proxy for rebuild cost at ε=0).
        initial_condition: Starting condition ∈ [0, 1]. Default: 1.0.
        years_horizon: Number of years over which to compare. Default: 30.
        epsilon: Automation level. Scales human-labor cost of all strategies.
        natural_decay_rate: Annual condition loss from unavoidable wear.
        writedown_threshold: Condition below which write-down triggers.
                             Default: 0.20 (matches writedown_trigger default).

    Returns:
        dict: {
          "asset_type":              str,
          "years_horizon":           int,
          "epsilon":                 float,
          "human_labor_fraction":    float,   (= 1 − ε)
          "continuous": {
            "total_eoh":             float,
            "annual_human_eoh":      float,
            "writedown_year":        None,
          },
          "deferred_to_writedown": {
            "total_eoh":             float,
            "writedown_year":        int | None,  (None if no writedown in horizon)
            "compounding_eoh":       float,
            "rebuild_eoh":           float,
          },
          "replace_at_writedown": {
            "total_eoh":             float,
            "writedown_year":        int | None,
            "replacement_eoh":       float,
          },
          "optimal_strategy":        str,    ("continuous" | "deferred_to_writedown"
                                              | "replace_at_writedown")
          "continuous_advantage":    float,  (deferred_total − continuous_total;
                                              positive = continuous cheaper)
        }

    Reference: Mission Statement §"Infrastructure EOH — the economic logic of
    infrastructure investment"; §"EOH and compounding — threshold-based, not
    exponential."
    """
    human_fraction = 1.0 - epsilon
    annual_human   = annual_eoh * human_fraction
    rebuild_eoh    = teh_value  * human_fraction
    replace_eoh    = rebuild_eoh * 0.85

    # --- Strategy 1: continuous ---
    continuous_total = annual_human * years_horizon

    # --- Strategies 2 & 3: deferred (shared condition projection) ---
    # Step condition forward one year at a time with zero fulfillment; stop as
    # soon as writedown triggers — avoids computing the full years_horizon list
    # when the threshold is hit early.
    neglect_period = [{"eoh_demanded": annual_eoh, "eoh_fulfilled": 0.0}]
    condition      = initial_condition
    writedown_year = None
    for yr in range(1, years_horizon + 1):
        condition = asset_condition(condition, neglect_period, natural_decay_rate)
        if writedown_trigger(condition, writedown_threshold):
            writedown_year = yr
            break

    if writedown_year is not None:
        # Compounding spike: physical EOH spike from years of neglect
        deferred_amount   = annual_eoh * writedown_year
        compounding_eoh   = eoh_compounding(deferred_amount, asset_type,
                                            float(writedown_year), epsilon)
        # Remaining years after rebuild/replace run on continuous maintenance
        post_writedown_yr = max(0, years_horizon - writedown_year)
        post_maint        = annual_human * post_writedown_yr

        # rebuild_eoh and replace_eoh already carry (1−ε) human fraction.
        # Compounding is physical; scale by human_fraction since automation
        # still handles a share of the crisis response.
        deferred_total = rebuild_eoh + compounding_eoh * human_fraction + post_maint
        replace_total  = replace_eoh + compounding_eoh * human_fraction + post_maint
    else:
        # No writedown within the horizon: deferred path costs 0 maintenance
        # (but note: this understates true long-term cost past the horizon).
        compounding_eoh = 0.0
        deferred_total  = 0.0
        replace_total   = 0.0

    if writedown_year is not None:
        totals  = {"continuous": continuous_total,
                   "deferred_to_writedown": deferred_total,
                   "replace_at_writedown":  replace_total}
        optimal = min(totals, key=lambda k: totals[k])
        # Positive = continuous cheaper; negative = a deferred strategy wins.
        # Uses the cheaper deferred option as the comparator.
        continuous_advantage: float | None = min(deferred_total, replace_total) - continuous_total
    else:
        # No writedown reached in the horizon: deferred strategies are
        # undercosted (0 maintenance, 0 rebuild within horizon). Only
        # continuous has complete-horizon data; do not compare.
        optimal = "continuous"
        continuous_advantage = None

    return {
        "asset_type":           asset_type,
        "years_horizon":        years_horizon,
        "epsilon":              epsilon,
        "human_labor_fraction": human_fraction,
        "continuous": {
            "total_eoh":        continuous_total,
            "annual_human_eoh": annual_human,
            "writedown_year":   None,
        },
        "deferred_to_writedown": {
            "total_eoh":       deferred_total,
            "writedown_year":  writedown_year,
            "compounding_eoh": compounding_eoh,
            "rebuild_eoh":     rebuild_eoh,
        },
        "replace_at_writedown": {
            "total_eoh":       replace_total,
            "writedown_year":  writedown_year,
            "replacement_eoh": replace_eoh,
        },
        "optimal_strategy":     optimal,
        "continuous_advantage": continuous_advantage,
    }


