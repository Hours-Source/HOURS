def eoh_health_indicators(
    total_eoh: float,
    fulfilled_eoh: float,
    epsilon: float = 0.40,
    deferred_eoh: float = 0.0,
    asset_type: str = "generic_infra",
    time_deferred: float = 0.0,
    registration_share: float | None = None,
) -> dict:
    """
    Phase 5.2: EOH health indicators for the current automation level.

    Measures four aspects of EOH system health:
    1. Deferred maintenance ratio: accumulated deferred EOH / total EOH.
       A rising ratio signals growing maintenance debt — compounding risk.
    2. EOH compounding rate: how much additional EOH the deferred backlog
       is generating. Threshold spike behavior (from Phase 2 eoh_dynamics).
    3. Registration coverage: what share of total EOH is in the collective
       ledger. Should rise with ε as care and stewardship registration grows.
    4. Care admission position: where the collective is on the care sigmoid.
       Should pace with ε — if lagging, human capital pipeline degrades.

    Args:
        total_eoh: Total EOH demand this period (all four domains).
        fulfilled_eoh: EOH actually fulfilled this period.
        epsilon: Automation level.
        deferred_eoh: Accumulated unfulfilled EOH from prior periods.
        asset_type: Asset type used for compounding profile. Default: "generic_infra".
        time_deferred: Years the current backlog has been accumulating.
        registration_share: Override for registration coverage [0,1].
                            If None, computed from total_registration_share(ε).

    Returns:
        dict: {
          "deferred_maintenance_ratio": float,    (deferred / total)
          "deferred_ratio_status":      str,      ("GREEN"/"YELLOW"/"RED")
          "eoh_compounding_amount":     float,    (extra EOH generated by backlog)
          "eoh_compounding_ratio":      float,    (compounding / deferred)
          "compounding_status":         str,
          "registration_coverage":      float,    (fraction in collective ledger)
          "registration_status":        str,
          "care_admission_share":       float,    (care sigmoid value at ε)
          "care_admission_status":      str,
          "fulfillment_rate":           float,    (fulfilled / total)
          "epsilon":                    float,
        }

    Reference: Mission Statement §"Deferred maintenance ratio"; §"EOH
    compounding — long slow accumulation, sharp threshold spike"
    """
    # 1. Deferred maintenance ratio
    deferred_ratio = deferred_eoh / max(total_eoh, 1.0)
    if deferred_ratio < DEFERRED_RATIO_WARN:
        deferred_status = "GREEN"
    elif deferred_ratio < DEFERRED_RATIO_CRIT:
        deferred_status = "YELLOW"
    else:
        deferred_status = "RED"

    # 2. EOH compounding (from Phase 2)
    if deferred_eoh > 0 and time_deferred > 0:
        compounding_amount = eoh_compounding(deferred_eoh, asset_type,
                                             time_deferred, epsilon)
        compounding_ratio = compounding_amount / max(deferred_eoh, 1.0)
    else:
        compounding_amount = 0.0
        compounding_ratio  = 0.0

    if compounding_ratio < COMPOUNDING_WARN:
        compounding_status = "GREEN"
    elif compounding_ratio < COMPOUNDING_CRIT:
        compounding_status = "YELLOW"
    else:
        compounding_status = "RED"

    # 3. Registration coverage
    if registration_share is None:
        registration_share = total_registration_share(epsilon)
    if epsilon < 0.10:
        # Subsistence bootstrapping: below the production sigmoid inflection (ε=0.10),
        # low registration is expected and healthy — the formal economy is intentionally tiny.
        reg_status = "GREEN"
    elif registration_share >= REGISTRATION_WARN:
        reg_status = "GREEN"
    elif registration_share >= REGISTRATION_CRIT:
        reg_status = "YELLOW"
    else:
        reg_status = "RED"

    # 4. Care admission position (sigmoid: where on the curve?)
    care_share = care_registration_share(epsilon)
    # Before the inflection point (ε=0.45), low care share is expected and healthy.
    # After the inflection, care share should be rising toward saturation.
    # RED/YELLOW only fire at high ε if care share is dramatically below the
    # sigmoid's own prediction — indicating an externally-modeled lag.
    # (Explicit lag testing is in care_registration_delay stress scenario.)
    _saturation = CARE_SIGMOID_DEFAULTS["saturation"]
    if epsilon < 0.45:
        care_status = "GREEN"  # early automation: low care share is expected
    elif care_share >= _saturation * CARE_ADMISSION_GREEN_FRAC:
        care_status = "GREEN"  # adequately progressed up the sigmoid
    elif care_share >= _saturation * CARE_ADMISSION_YELLOW_FRAC:
        care_status = "YELLOW"
    else:
        care_status = "RED"   # severely lagging at high ε

    fulfillment_rate = fulfilled_eoh / max(total_eoh, 1.0)

    # new-4: Personal EOH registration indicator.
    # At ε=0, personal EOH is entirely private (off-ledger). Rising share means
    # more of the population's biological obligations are collectively recognized
    # and funded — a key signal of the personal-to-collective ledger transition.
    pers_reg_share = personal_eoh_registration_share(epsilon)
    # Status mirrors non-personal registration thresholds
    if pers_reg_share >= REGISTRATION_WARN:
        pers_reg_status = "GREEN"
    elif pers_reg_share >= REGISTRATION_CRIT:
        pers_reg_status = "YELLOW"
    else:
        pers_reg_status = "RED"

    return {
        "deferred_maintenance_ratio":  deferred_ratio,
        "deferred_ratio_status":       deferred_status,
        "eoh_compounding_amount":      compounding_amount,
        "eoh_compounding_ratio":       compounding_ratio,
        "compounding_status":          compounding_status,
        "registration_coverage":       registration_share,
        "registration_status":         reg_status,
        "personal_registration_share": pers_reg_share,
        "personal_registration_status": pers_reg_status,
        "care_admission_share":        care_share,
        "care_admission_status":       care_status,
        "fulfillment_rate":            fulfillment_rate,
        "epsilon":                     epsilon,
    }


