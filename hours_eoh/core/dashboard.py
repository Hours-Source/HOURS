def fiscal_health_check(
    trust_balance: float,
    labor_income: float,
    capital_stock_teh: float,
    capital_age_ratio: float,
    population: float,
    floor_teh: float,
    epsilon: float = 0.40,
    suff_levy_rate: float = SUFF_LEVY_RATE,
    dep_rate: float = DEP_RATE,
    div_rate: float = DIV_RATE,
    baseline_basket_cost: float = MEANINGFUL_ACTIVITY_TEH_BASE,
    ecosystem_health: float = 0.70,
    deferred_ecological: float = 0.0,
    eco_eoh_override: float | None = None,
    capital_eoh_eliminated: float = 0.0,
) -> dict:
    """
    Phase 5.3: Fiscal health check — trust solvency, purchasing power, levy sufficiency.

    Three pillars of fiscal health:
    1. Trust solvency: Can the Trust fund both stewardship and the sufficiency
       guarantee simultaneously? A solvent trust has positive surplus_deficit.
    2. Floor purchasing power trend: Is the floor PP index ≥ 1.0? Is it
       materially above baseline? (Principle 5 — it must never decline.)
    3. Levy sufficiency: Do levies cover at least LEVY_SUFFICIENCY_WARN fraction
       of the guarantee cost? Ensures fiscal burden sharing across the economy.

    Args:
        trust_balance: Current trust fund balance (TEH).
        labor_income: Annual TEH earned by workers.
        capital_stock_teh: Total capital stock value (TEH).
        capital_age_ratio: Mean asset age as fraction of design life.
        population: Total population.
        floor_teh: Sufficiency floor in TEH/year.
        epsilon: Automation level.
        suff_levy_rate: Sufficiency levy rate on labor income.
        dep_rate: Annual depreciation rate of trust.
        div_rate: Fraction of depreciation paid as dividend.
        baseline_basket_cost: Basket cost at ε=0.
        ecosystem_health: Ecosystem state ∈ [0, 1]. Used for ecological
            allocation sizing. Default: 0.70.
        deferred_ecological: Accumulated deferred ecological EOH. Default: 0.0.
        eco_eoh_override: Pre-computed ecological EOH from the pipeline.
            When provided, ecological_allocation() uses it directly rather than
            recomputing. Mirrors the infra_eoh_override pattern in fiscal_snapshot().
        capital_eoh_eliminated: EOH eliminated by capital stock, passed to
            stewardship_allocation() to match the pipeline's accounting.

    Returns:
        dict: {
          "trust_solvent":       bool,
          "trust_status":        str,   ("GREEN"/"RED")
          "trust_surplus_deficit": float,
          "pp_index":            float,
          "pp_status":           str,   ("GREEN"/"YELLOW"/"RED")
          "pp_gain_pct":         float,
          "levy_revenue":        float,
          "guarantee_cost":      float,
          "levy_to_guarantee_ratio": float,
          "levy_status":         str,
          "ecological_cost":     float,
          "ecological_status":   str,   ("GREEN"/"YELLOW"/"RED")
          "epsilon":             float,
        }

    Reference: Mission Statement §"Principle 2 — never depend on production for
    survival"; §"Principle 5 — The floor rises with automation; it never falls"
    """
    levies  = levy_collection(labor_income, {"sufficiency": suff_levy_rate})
    # new-13: translate capital_eoh_eliminated to infra_eoh_override, matching the
    # fiscal_snapshot() accounting pattern so stewardship sizing is in sync with
    # what total_eoh() has already eliminated.
    _infra_override = None
    if capital_eoh_eliminated > 0.0:
        from hours_eoh.core.eoh_generation import infrastructure_eoh as _infra_eoh
        _raw_infra = _infra_eoh(capital_stock_teh, capital_age_ratio, epsilon)
        _reduction  = max(0.0, 1.0 - capital_eoh_eliminated / max(_raw_infra, 1.0))
        _infra_override = _raw_infra * _reduction
    stew    = stewardship_allocation(capital_stock_teh, capital_age_ratio,
                                     epsilon, available_teh=trust_balance,
                                     infra_eoh_override=_infra_override)
    # new-3: ecological allocation is co-equal with stewardship — both draw
    # from the full Trust balance independently (neither is residual).
    eco     = ecological_allocation(ecosystem_health, epsilon,
                                    available_teh=trust_balance,
                                    deferred=deferred_ecological,
                                    eco_eoh_override=eco_eoh_override)
    guar    = sufficiency_guarantee(population, epsilon)
    trust   = trust_management(trust_balance, levies["total_levied"],
                                stew["teh_allocated"] + eco["teh_allocated"],
                                guar["total_cost_teh"],
                                dep_rate, div_rate, epsilon)
    pp      = floor_purchasing_power(floor_teh, epsilon, baseline_basket_cost)

    # Trust status
    trust_status = "GREEN" if trust["solvent"] else "RED"

    # PP status: must be ≥ 1.0 (Principle 5 hard requirement)
    # YELLOW if pp_index lags the continuous expected gain: threshold = 1 + slope×ε.
    # At ε=0.40 this equals PP_INDEX_WARN (1.05); removes the ε=0.40 blind spot.
    pp_index = pp["pp_index"]
    pp_warn_threshold = 1.0 + PP_INDEX_WARN_SLOPE * epsilon
    if pp_index < 1.0 - 1e-9:
        pp_status = "RED"     # Principle 5 violation — never allowed
    elif pp_index < pp_warn_threshold:
        pp_status = "YELLOW"  # lagging expected PP rise for this automation level
    else:
        pp_status = "GREEN"

    # Levy sufficiency: levy revenue vs. guarantee cost
    levy_revenue = levies["total_levied"]
    guarantee_cost = guar["total_cost_teh"]
    levy_ratio = levy_revenue / max(guarantee_cost, 1.0)
    if levy_ratio >= LEVY_SUFFICIENCY_WARN:
        levy_status = "GREEN"
    else:
        levy_status = "YELLOW"  # levy covers less than half of guarantee; trust must cover more

    # new-3: ecological status — healthy when allocated amount is covered by Trust
    eco_cost = eco["teh_allocated"]
    eco_status = "GREEN" if eco_cost <= trust_balance * 0.30 else (
                 "YELLOW" if eco_cost <= trust_balance * 0.60 else "RED")

    return {
        "trust_solvent":           trust["solvent"],
        "trust_status":            trust_status,
        "trust_surplus_deficit":   trust["surplus_deficit"],
        "pp_index":                pp_index,
        "pp_status":               pp_status,
        "pp_gain_pct":             pp["pp_gain_pct"],
        "levy_revenue":            levy_revenue,
        "guarantee_cost":          guarantee_cost,
        "levy_to_guarantee_ratio": levy_ratio,
        "levy_status":             levy_status,
        "ecological_cost":         eco_cost,
        "ecological_status":       eco_status,
        "epsilon":                 epsilon,
    }


